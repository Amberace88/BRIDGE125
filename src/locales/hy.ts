// Armenian: sentences end with “։”, questions mark the stressed vowel with “՞”.
// Card vocabulary: պիկ ♠, խաչ ♣, սիրտ ♥, աղյուս ♦; վալետ, դամա, թագավոր, տուզ; մաստ = suit.

/** Subject form of a player name: Armenian adds the definite article (-ը after a consonant, -ն after a vowel; hyphenated for non-Armenian names). */
function def(name: string): string {
  const last = name.trim().slice(-1);
  if (!last) return name;
  const armenian = /[Ա-և]/.test(last);
  const vowel = /[աեէըիոօւaeiouyаеёиоуыэюяіїєў]/i.test(last);
  return name + (armenian ? '' : '-') + (vowel ? 'ն' : 'ը');
}

