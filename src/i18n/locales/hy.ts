// Armenian (as in src/locales/hy.ts): sentences end with “։”, the stressed vowel of a question takes “՞”.
// Card vocabulary: պիկի դամա, վալետ, տուզ, թագավոր; մաստ = suit; կապուկ = deck.

/** Subject form of a player name (as in src/locales/hy.ts): the definite article -ը after a consonant, -ն after a vowel; hyphenated for non-Armenian names. */
function def(name: string): string {
  const s = String(name), last = s.trim().slice(-1);
  if (!last) return s;
  const armenian = /[Ա-և]/.test(last);
  const vowel = /[աեէըիոօւaeiouyаеёиоуыэюяіїєў]/i.test(last);
  return s + (armenian ? '' : '-') + (vowel ? 'ն' : 'ը');
}

